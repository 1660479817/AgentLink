/**
 * 国家码 → IANA 时区名。`GLOBAL`、未知代码、`null` 都返回 null：
 * 推不出来就不推，页面自己退回 UTC。
 */
export function timezoneOf(code) {
  const key = typeof code === "string" ? code.trim().toUpperCase() : "";
  if (!/^[A-Z]{2}$/.test(key)) return null;
  return COUNTRY_TIMEZONE[key] || null;
}
